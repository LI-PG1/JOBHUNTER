    '',
    '## 90 秒完整版',
    '（口播稿，约 220~280 字，依次包含：①称呼问候 ②教育背景：学校/专业/学历 ③经历与成果：按岗位方向选 2~3 个可量化成果（数字必须来自用户简历，禁止新增）④技术栈：只列与岗位强相关的技能 ⑤为什么选择该公司该岗位 + 能为公司带来什么。要求连贯口语化，像当面说话。）',
    '',
    '## 60 秒精简版',
    '（约 100~140 字：①称呼问候 ②核心经历一句话（含 1 个最有分量的数字）③技术栈 ④期待。）',
