def build_generate_prompt(file: dict[str, Any], context: str, feedback: str = "") -> str:
    """单个文件的生成 prompt：上下文 + 本次文件 hint + （回炉时）审核意见。"""
    parts = [
        "【上下文】\n" + context,
        "【本次要生成的文件】" + file["name"] + ".md",
        file["hint"],
    ]
    if feedback:
        parts.append("\n" + feedback)
    parts.append("\n请输出《" + file["name"] + "》完整 Markdown 内容：")
    return "\n".join(parts)
